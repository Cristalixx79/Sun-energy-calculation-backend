"""
Функция-singleton для "текущего" пользователя.

Авторизация в этой лабораторной работе не реализуется (появится в
лаб. №4), поэтому пользователь-создатель зафиксирован константой.
Чтобы вся кодовая база использовала ровно одно место для получения
этого id (а не россыпь литералов `1` по файлам), id отдаётся через
функцию-singleton `get_current_user_id`.

`lru_cache(maxsize=1)` гарантирует, что тело функции выполнится
только один раз за время жизни процесса и дальше будет возвращаться
закешированное значение — это стандартный приём реализации singleton
на чистых функциях в Python, без отдельного класса.

Когда в лаб. №4 появится настоящая авторизация, достаточно будет
поменять реализацию только этой функции (например, читать id из
JWT/сессии) — остальной код, вызывающий `get_current_user_id()`,
менять не придётся.
"""

from functools import lru_cache

# id зафиксированного пользователя-создателя.
CURRENT_USER_ID: int = 1


@lru_cache(maxsize=1)
def get_current_user_id() -> int:
    return CURRENT_USER_ID
